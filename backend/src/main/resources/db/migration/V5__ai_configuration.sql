-- 3 sprintas: DI parametrai, kuriuos nustato administratorius (NI-20, FR-41).
-- Kiekvienas pakeitimas – naujas įrašas; galioja naujausias. Jei įrašų nėra, naudojamas aplinkos kintamasis
-- GEMINI_MODEL ir konfigūracijoje nurodytas dienos limitas (DIA-4).
CREATE TABLE ai_configuration (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    model                  VARCHAR(100) NOT NULL,
    daily_generation_limit INTEGER      NOT NULL CHECK (daily_generation_limit BETWEEN 1 AND 20),
    changed_at             TIMESTAMPTZ  NOT NULL,
    changed_by             BIGINT       REFERENCES app_user (id) ON DELETE SET NULL
);
CREATE INDEX idx_ai_configuration_changed_at ON ai_configuration (changed_at);
