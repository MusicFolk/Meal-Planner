-- Dienos kaloringumo nuokrypis nuo paros poreikio procentais (FR-13)
ALTER TABLE plan_day ADD COLUMN deviation_percent NUMERIC(5, 1);

UPDATE plan_day pd
SET deviation_percent = round((pd.total_calories - mp.daily_calories) * 100.0 / mp.daily_calories, 1)
FROM meal_plan mp
WHERE mp.id = pd.meal_plan_id AND mp.daily_calories > 0;

-- Vienas plano generavimas su DI. Įrašas išsaugomas ir nesėkmės atveju (FR-14).
-- Demonstraciniai planai generavimo įrašo neturi, nepavykęs generavimas plano nesukuria.
CREATE TABLE plan_generation (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id     BIGINT      NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    meal_plan_id  BIGINT      UNIQUE REFERENCES meal_plan (id) ON DELETE SET NULL,
    started_at    TIMESTAMPTZ NOT NULL,
    finished_at   TIMESTAMPTZ,
    status        VARCHAR(20) NOT NULL CHECK (status IN ('IN_PROGRESS', 'SUCCESS', 'FAILED')),
    model         VARCHAR(50) NOT NULL,
    error_message VARCHAR(500)
);
CREATE INDEX idx_plan_generation_client ON plan_generation (client_id, started_at);
-- Vienu metu klientas gali turėti tik vieną vykdomą generavimą (FR-09, PLN-2)
CREATE UNIQUE INDEX uq_plan_generation_in_progress ON plan_generation (client_id) WHERE status = 'IN_PROGRESS';

-- Vienas DI kvietimas vienam valgymo tipui (3..9 viename generavime). Užklausa ir atsakymas – JSONB (NFR-05)
CREATE TABLE ai_generation_request (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_generation_id BIGINT      NOT NULL REFERENCES plan_generation (id) ON DELETE CASCADE,
    meal_type          VARCHAR(10) NOT NULL CHECK (meal_type IN ('BREAKFAST', 'LUNCH', 'DINNER')),
    attempt            INTEGER     NOT NULL CHECK (attempt BETWEEN 1 AND 3),
    target_calories    INTEGER     NOT NULL,
    request_json       JSONB       NOT NULL,
    response_json      JSONB,
    result             VARCHAR(30) NOT NULL CHECK (result IN ('VALID', 'INVALID_SCHEMA', 'INVALID_PRODUCT',
                                                              'PORTION_OUT_OF_RANGE', 'TIMEOUT', 'API_ERROR')),
    duration_ms        INTEGER     NOT NULL,
    created_at         TIMESTAMPTZ NOT NULL,
    UNIQUE (plan_generation_id, meal_type, attempt)
);
