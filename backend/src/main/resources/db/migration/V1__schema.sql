-- Meal Planner – pradinė DB schema (1 sprintas, 29 pav. klasių diagrama)

-- Naudotojai: Client, Dietitian ir Administrator saugomi vienoje lentelėje, tipą nurodo role
CREATE TABLE app_user (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role                  VARCHAR(20)  NOT NULL CHECK (role IN ('CLIENT', 'DIETITIAN', 'ADMIN')),
    email                 VARCHAR(100) NOT NULL UNIQUE,
    password_hash         VARCHAR(100) NOT NULL,
    first_name            VARCHAR(50)  NOT NULL,
    last_name             VARCHAR(50),
    blocked               BOOLEAN      NOT NULL DEFAULT FALSE,
    failed_login_attempts INTEGER      NOT NULL DEFAULT 0,
    locked_until          TIMESTAMPTZ,
    created_at            TIMESTAMPTZ  NOT NULL DEFAULT now(),
    -- Client
    health_data_consent   BOOLEAN,
    theme                 VARCHAR(10) CHECK (theme IN ('LIGHT', 'DARK', 'SYSTEM')),
    first_day_of_week     VARCHAR(10) CHECK (first_day_of_week IN ('MONDAY', 'SUNDAY')),
    -- Dietitian
    must_change_password  BOOLEAN
);

CREATE TABLE subscription (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id     BIGINT      NOT NULL UNIQUE REFERENCES app_user (id) ON DELETE CASCADE,
    trial_ends_at TIMESTAMPTZ NOT NULL,
    paid_until    TIMESTAMPTZ
);

CREATE TABLE notification (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id  BIGINT       NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    message    VARCHAR(500) NOT NULL,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    read       BOOLEAN      NOT NULL DEFAULT FALSE
);
CREATE INDEX idx_notification_client ON notification (client_id);

-- Produktai ir alergenai
CREATE TABLE allergen (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(30) NOT NULL UNIQUE,
    name VARCHAR(50) NOT NULL
);

CREATE TABLE product (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name      VARCHAR(100) NOT NULL,
    fdc_id    INTEGER      NOT NULL UNIQUE,
    category  VARCHAR(20)  NOT NULL CHECK (category IN ('MEAT_FISH', 'DAIRY_EGGS', 'GRAINS', 'VEGETABLES',
                                                          'FRUITS', 'NUTS_SEEDS', 'FATS_SPICES', 'OTHER')),
    kcal      INTEGER      NOT NULL,
    protein_g NUMERIC(6, 2) NOT NULL,
    fat_g     NUMERIC(6, 2) NOT NULL,
    carbs_g   NUMERIC(6, 2) NOT NULL
);

CREATE TABLE product_allergen (
    product_id  BIGINT NOT NULL REFERENCES product (id) ON DELETE CASCADE,
    allergen_id BIGINT NOT NULL REFERENCES allergen (id) ON DELETE CASCADE,
    PRIMARY KEY (product_id, allergen_id)
);

-- Anketa
CREATE TABLE questionnaire (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id       BIGINT       NOT NULL UNIQUE REFERENCES app_user (id) ON DELETE CASCADE,
    height_cm       INTEGER      NOT NULL CHECK (height_cm BETWEEN 100 AND 250),
    weight_kg       NUMERIC(4, 1) NOT NULL CHECK (weight_kg BETWEEN 30 AND 300),
    age             INTEGER      NOT NULL CHECK (age BETWEEN 18 AND 100),
    gender          VARCHAR(10)  NOT NULL CHECK (gender IN ('MALE', 'FEMALE')),
    activity_level  VARCHAR(20)  NOT NULL CHECK (activity_level IN ('SEDENTARY', 'LIGHT', 'MODERATE', 'ACTIVE', 'VERY_ACTIVE')),
    goal            VARCHAR(20)  NOT NULL CHECK (goal IN ('LOSE_WEIGHT', 'MAINTAIN', 'GAIN_MUSCLE')),
    chronic_disease BOOLEAN      NOT NULL,
    bmi             NUMERIC(4, 1) NOT NULL,
    daily_calories  INTEGER      NOT NULL,
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE questionnaire_allergen (
    questionnaire_id BIGINT NOT NULL REFERENCES questionnaire (id) ON DELETE CASCADE,
    allergen_id      BIGINT NOT NULL REFERENCES allergen (id),
    PRIMARY KEY (questionnaire_id, allergen_id)
);

CREATE TABLE questionnaire_disliked_product (
    questionnaire_id BIGINT NOT NULL REFERENCES questionnaire (id) ON DELETE CASCADE,
    product_id       BIGINT NOT NULL REFERENCES product (id),
    PRIMARY KEY (questionnaire_id, product_id)
);

-- Mitybos planas. client_id IS NULL – demonstracinis plano šablonas (1 sprintas)
CREATE TABLE meal_plan (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id      BIGINT      REFERENCES app_user (id) ON DELETE CASCADE,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    active         BOOLEAN     NOT NULL DEFAULT FALSE,
    ai_generated   BOOLEAN     NOT NULL DEFAULT FALSE,
    daily_calories INTEGER
);
CREATE INDEX idx_meal_plan_client ON meal_plan (client_id);
CREATE UNIQUE INDEX uq_meal_plan_active ON meal_plan (client_id) WHERE active;

CREATE TABLE plan_day (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    meal_plan_id   BIGINT  NOT NULL REFERENCES meal_plan (id) ON DELETE CASCADE,
    day_number     INTEGER NOT NULL CHECK (day_number BETWEEN 1 AND 7),
    total_calories INTEGER NOT NULL DEFAULT 0,
    UNIQUE (meal_plan_id, day_number)
);

CREATE TABLE meal (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_day_id     BIGINT      NOT NULL REFERENCES plan_day (id) ON DELETE CASCADE,
    type            VARCHAR(10) NOT NULL CHECK (type IN ('BREAKFAST', 'LUNCH', 'DINNER')),
    target_calories INTEGER,
    UNIQUE (plan_day_id, type)
);

CREATE TABLE dish (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    meal_id       BIGINT       NOT NULL UNIQUE REFERENCES meal (id) ON DELETE CASCADE,
    name          VARCHAR(150) NOT NULL,
    portion_grams INTEGER      NOT NULL DEFAULT 0,
    kcal          INTEGER      NOT NULL DEFAULT 0,
    protein_g     NUMERIC(6, 1) NOT NULL DEFAULT 0,
    fat_g         NUMERIC(6, 1) NOT NULL DEFAULT 0,
    carbs_g       NUMERIC(6, 1) NOT NULL DEFAULT 0
);

CREATE TABLE recipe (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dish_id BIGINT NOT NULL UNIQUE REFERENCES dish (id) ON DELETE CASCADE
);

CREATE TABLE ingredient (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipe_id  BIGINT  NOT NULL REFERENCES recipe (id) ON DELETE CASCADE,
    product_id BIGINT  NOT NULL REFERENCES product (id),
    grams      INTEGER NOT NULL CHECK (grams > 0)
);

CREATE TABLE recipe_step (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipe_id   BIGINT        NOT NULL REFERENCES recipe (id) ON DELETE CASCADE,
    step_number INTEGER       NOT NULL,
    description VARCHAR(1000) NOT NULL,
    UNIQUE (recipe_id, step_number)
);

CREATE TABLE shopping_list (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    meal_plan_id BIGINT NOT NULL UNIQUE REFERENCES meal_plan (id) ON DELETE CASCADE
);

CREATE TABLE shopping_list_item (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shopping_list_id BIGINT  NOT NULL REFERENCES shopping_list (id) ON DELETE CASCADE,
    product_id       BIGINT  NOT NULL REFERENCES product (id),
    total_grams      INTEGER NOT NULL,
    purchased        BOOLEAN NOT NULL DEFAULT FALSE,
    UNIQUE (shopping_list_id, product_id)
);

-- Mokėjimai. Ištrynus klientą, mokėjimas nuasmeninamas (client_id = NULL) – lieka suma ir data (FR-46)
CREATE TABLE payment (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference           UUID          NOT NULL UNIQUE,
    client_id           BIGINT        REFERENCES app_user (id) ON DELETE SET NULL,
    amount              NUMERIC(8, 2) NOT NULL,
    purpose             VARCHAR(20)   NOT NULL CHECK (purpose IN ('SUBSCRIPTION', 'REVIEW')),
    method              VARCHAR(20)   NOT NULL CHECK (method IN ('BANK_LINK', 'CARD')),
    status              VARCHAR(20)   NOT NULL CHECK (status IN ('PENDING', 'PAID', 'FAILED')),
    created_at          TIMESTAMPTZ   NOT NULL DEFAULT now(),
    -- Peržiūros užsakymo duomenys, kol laukiama banko patvirtinimo
    review_meal_plan_id BIGINT        REFERENCES meal_plan (id) ON DELETE SET NULL,
    review_question     VARCHAR(500)
);

-- Peržiūros užklausos ir komentarai
CREATE TABLE review_request (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id    BIGINT      NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    meal_plan_id BIGINT      NOT NULL REFERENCES meal_plan (id) ON DELETE CASCADE,
    payment_id   BIGINT      UNIQUE REFERENCES payment (id) ON DELETE SET NULL,
    dietitian_id BIGINT      REFERENCES app_user (id) ON DELETE SET NULL,
    question     VARCHAR(500),
    status       VARCHAR(20) NOT NULL CHECK (status IN ('PENDING', 'IN_REVIEW', 'COMPLETED')),
    submitted_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    reviewed_at  TIMESTAMPTZ
);
CREATE INDEX idx_review_request_status ON review_request (status);

CREATE TABLE comment (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    review_request_id BIGINT        NOT NULL REFERENCES review_request (id) ON DELETE CASCADE,
    dish_id           BIGINT        REFERENCES dish (id) ON DELETE CASCADE,
    text              VARCHAR(2000) NOT NULL,
    created_at        TIMESTAMPTZ   NOT NULL DEFAULT now()
);

